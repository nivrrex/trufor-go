// func gelu8(x *float32, y *float32)
// 对 8 个元素计算精确 GELU = 0.5*x*(1+erf(x/sqrt2))。
// erf 用 Abramowitz-Stegun 7.1.26（|误差| < 1.5e-7），exp 复用与 exp8 相同的多项式。
TEXT ·gelu8(SB), NOSPLIT, $0-16
	MOVQ x+0(FP), SI
	MOVQ y+8(FP), DI
	VMOVUPS 0(SI), Y0                 // x
	VANDPS ·cabsm<>(SB), Y0, Y1       // |x|
	VANDPS ·csignm<>(SB), Y0, Y2      // 符号位
	VMULPS ·cinvsqrt2<>(SB), Y1, Y1   // u = |x|/sqrt2
	VMULPS ·cp<>(SB), Y1, Y3
	VMOVAPS ·cones<>(SB), Y4
	VADDPS Y4, Y3, Y3                 // 1 + p*u
	VDIVPS Y3, Y4, Y3                 // t = 1/(1+p*u)
	VMOVAPS ·ca5<>(SB), Y5
	VMOVAPS ·ca4<>(SB), Y6
	VFMADD231PS Y3, Y5, Y6
	VMOVAPS ·ca3<>(SB), Y5
	VFMADD231PS Y3, Y6, Y5
	VMOVAPS ·ca2<>(SB), Y6
	VFMADD231PS Y3, Y5, Y6
	VMOVAPS ·ca1<>(SB), Y5
	VFMADD231PS Y3, Y6, Y5
	VMULPS Y3, Y5, Y5                 // poly(t)

	// e = exp(-u*u)
	VMULPS Y1, Y1, Y7
	VXORPS ·csignm<>(SB), Y7, Y7
	VMAXPS ·clow<>(SB), Y7, Y7
	VMULPS ·clog2e<>(SB), Y7, Y8
	VADDPS ·cmagic<>(SB), Y8, Y9
	VSUBPS ·cmagic<>(SB), Y9, Y9      // k
	VMULPS ·cln2hi<>(SB), Y9, Y10
	VSUBPS Y10, Y7, Y10
	VMULPS ·cln2lo<>(SB), Y9, Y11
	VSUBPS Y11, Y10, Y10              // z
	VMOVAPS ·c0<>(SB), Y11
	VMOVAPS ·c1<>(SB), Y12
	VFMADD231PS Y10, Y11, Y12
	VMOVAPS ·c2<>(SB), Y11
	VFMADD231PS Y10, Y12, Y11
	VMOVAPS ·c3<>(SB), Y12
	VFMADD231PS Y10, Y11, Y12
	VMOVAPS ·c4<>(SB), Y11
