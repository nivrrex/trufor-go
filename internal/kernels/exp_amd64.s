	MOVQ x+0(FP), SI
	MOVQ y+8(FP), DI
	VMOVUPS 0(SI), Y0
	VMAXPS ·clow<>(SB), Y0, Y0
	VMULPS ·clog2e<>(SB), Y0, Y1      // t = x*log2e
	VADDPS ·cmagic<>(SB), Y1, Y2
	VSUBPS ·cmagic<>(SB), Y2, Y2      // k = round(t)
	VMULPS ·cln2hi<>(SB), Y2, Y3
	VSUBPS Y3, Y0, Y3                 // x - k*ln2_hi
	VMULPS ·cln2lo<>(SB), Y2, Y14
	VSUBPS Y14, Y3, Y3                // z = x - k*ln2_hi - k*ln2_lo
	VMOVAPS ·c0<>(SB), Y4
	VMOVAPS ·c1<>(SB), Y5
	VFMADD231PS Y3, Y4, Y5
	VMOVAPS ·c2<>(SB), Y6
	VFMADD231PS Y3, Y5, Y6
	VMOVAPS ·c3<>(SB), Y7
	VFMADD231PS Y3, Y6, Y7
	VMOVAPS ·c4<>(SB), Y8
	VFMADD231PS Y3, Y7, Y8
	VMOVAPS ·c5<>(SB), Y9
