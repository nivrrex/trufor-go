// func micro6x16(ap *float32, bp *float32, c *float32, kc int, ldc int)
// C[6x16] += A[6 x kc] * B[kc x 16]
// ap 为按 k 交织的 A 微面板（每个 k 连续存放 6 行，即 ap[p*6+r]），
// bp 行跨度固定 16，c 行跨度为 ldc。
// 参数偏移：ap=0 bp=8 c=16 kc=24 ldc=32（共 40 字节）
TEXT ·micro6x16(SB), NOSPLIT, $0-40
	MOVQ ap+0(FP), SI
	MOVQ bp+8(FP), DX
	MOVQ c+16(FP), DI
	MOVQ kc+24(FP), CX
	MOVQ ldc+32(FP), R10
	SHLQ $2, R10   // ldc 字节

	// 载入 C
	MOVQ DI, R11
	VMOVUPS 0(R11), Y0
	VMOVUPS 32(R11), Y1
	ADDQ R10, R11
	VMOVUPS 0(R11), Y2
	VMOVUPS 32(R11), Y3
	ADDQ R10, R11
	VMOVUPS 0(R11), Y4
	VMOVUPS 32(R11), Y5
	ADDQ R10, R11
	VMOVUPS 0(R11), Y6
	VMOVUPS 32(R11), Y7
	ADDQ R10, R11
	VMOVUPS 0(R11), Y8
	VMOVUPS 32(R11), Y9
	ADDQ R10, R11
	VMOVUPS 0(R11), Y10
	VMOVUPS 32(R11), Y11

	TESTQ CX, CX
	JZ store

loop:
	VMOVUPS 0(DX), Y12
	VMOVUPS 32(DX), Y13

	VBROADCASTSS 0(SI), Y14
	VFMADD231PS Y14, Y12, Y0
	VFMADD231PS Y14, Y13, Y1
	VBROADCASTSS 4(SI), Y14
	VFMADD231PS Y14, Y12, Y2
	VFMADD231PS Y14, Y13, Y3
	VBROADCASTSS 8(SI), Y14
	VFMADD231PS Y14, Y12, Y4
	VFMADD231PS Y14, Y13, Y5
	VBROADCASTSS 12(SI), Y14
	VFMADD231PS Y14, Y12, Y6
	VFMADD231PS Y14, Y13, Y7
	VBROADCASTSS 16(SI), Y14
	VFMADD231PS Y14, Y12, Y8
	VFMADD231PS Y14, Y13, Y9
	VBROADCASTSS 20(SI), Y14
	VFMADD231PS Y14, Y12, Y10
	VFMADD231PS Y14, Y13, Y11

	ADDQ $24, SI     // 下一个 k：A 微面板中 6 个 float32
	ADDQ $64, DX     // 下一行 B（16 个 float32）
	DECQ CX
	JNZ loop

store:
	MOVQ DI, R11
	VMOVUPS Y0, 0(R11)
	VMOVUPS Y1, 32(R11)
	ADDQ R10, R11
	VMOVUPS Y2, 0(R11)
	VMOVUPS Y3, 32(R11)
	ADDQ R10, R11
	VMOVUPS Y4, 0(R11)
	VMOVUPS Y5, 32(R11)
	ADDQ R10, R11
	VMOVUPS Y6, 0(R11)
	VMOVUPS Y7, 32(R11)
	ADDQ R10, R11
	VMOVUPS Y8, 0(R11)
	VMOVUPS Y9, 32(R11)
	ADDQ R10, R11
	VMOVUPS Y10, 0(R11)
	VMOVUPS Y11, 32(R11)
	VZEROUPPER
	RET

